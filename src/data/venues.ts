import type { DayRange, Photo, Schedule, Venue } from '@/types';

/**
 * Seed venue database for the launch metro (Houston).
 *
 * Composition is deliberate: bars outnumber every other vertical, matching the
 * PRD's own observation (Open Question 10) that bars will dominate the corpus.
 * The set also carries the awkward cases on purpose — a venue that is a
 * restaurant until 10 PM and a club after, dual Bar/Lounge assignment, a
 * permanently closed listing with a successor, a Consumer Alert, and two paid
 * placements — so the UI has to handle them rather than pretending they are rare.
 */

type DaySpec = [string, string] | null;

/** Days are indexed 0 = Sunday to match Date#getDay. */
const w = (
  su: DaySpec, mo: DaySpec, tu: DaySpec, we: DaySpec, th: DaySpec, fr: DaySpec, sa: DaySpec,
): (DayRange | null)[] =>
  [su, mo, tu, we, th, fr, sa].map((d) => (d ? { open: d[0], close: d[1] } : null));

const sched = (
  kind: Schedule['kind'],
  label: string,
  days: (DayRange | null)[],
  updatedAt: string,
): Schedule => ({ kind, label, days, updatedAt });

const pic = (
  id: string,
  album: Photo['album'],
  caption: string,
  by: Photo['by'],
  alt: string,
): Photo => ({ id, album, caption, by, alt });

